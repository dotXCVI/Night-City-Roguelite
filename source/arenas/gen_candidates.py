#!/usr/bin/env python3
"""Night City Roguelite - arena candidates for the scout.

Turns candidates.tsv into r6/scripts/NightCityRoguelite/Data/ArenaCandidates.reds.
Each candidate gets the gangs of its district (the ones that hold it in the
open world) as factions.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'r6', 'scripts', 'NightCityRoguelite', 'Data', 'ArenaCandidates.reds')

FACTIONS = {
    'watson/kabuki': ['TygerClaws', 'Maelstrom'],
    'watson/little_china': ['TygerClaws', 'Maelstrom'],
    'watson/northside': ['Maelstrom', 'Scavengers'],
    'westbrook/japantown': ['TygerClaws'],
    'westbrook/charter_hill': ['TygerClaws', 'Arasaka'],
    'city_center/downtown': ['Animals', 'TygerClaws'],
    'city_center/corpo_plaza': ['Arasaka', 'Militech'],
    'heywood/glen': ['Valentinos', 'SixthStreet'],
    'heywood/vista_del_rey': ['Valentinos'],
    'heywood/wellsprings': ['Valentinos'],
    'santo_domingo/arroyo': ['SixthStreet', 'Maelstrom'],
    'santo_domingo/rancho_coronado': ['SixthStreet', 'Animals'],
    'pacifica/coastview': ['VoodooBoys', 'Animals'],
    'pacifica/west_wind_estates': ['VoodooBoys', 'Animals'],
    'badlands/inland_avenue': ['Wraiths', 'Scavengers'],
    'badlands/se1': ['Wraiths', 'Scavengers'],
    'dogtown': ['Barghest'],
    'story/maelstrom': ['Maelstrom'],
    'story/wraiths': ['Wraiths'],
    'story/arasaka': ['Arasaka'],
    'story/voodoo': ['VoodooBoys'],
    'story/tygers': ['TygerClaws', 'Arasaka'],
    'story/barghest': ['Barghest'],
    'story/militech': ['Militech', 'Barghest'],
}


def main():
    rows = []
    for line in open(os.path.join(HERE, 'candidates.tsv')):
        if not line.strip() or line.startswith('#'):
            continue
        kind, cid, district, x, y, z = line.rstrip('\n').split('\t')
        rows.append((kind, cid, district, x, y, z))
    out = [
        '// -----------------------------------------------------------------------------',
        '// Night City Roguelite - arena candidates (generated)',
        '// -----------------------------------------------------------------------------',
        '// Generated by source/arenas/gen_candidates.py from source/arenas/candidates.tsv',
        f'// - edit the TSV, not this file. {len(rows)} candidates for the arena scout',
        '// (Combat/ArenaScout.reds, dev tools only).',
        '// -----------------------------------------------------------------------------',
        '',
        'module NightCityRoguelite',
        '',
        'public abstract class RLArenaCandidates {',
        '  public static func All() -> array<ref<RLArenaCandidate>> {',
        '    let list: array<ref<RLArenaCandidate>>;',
    ]
    for kind, cid, district, x, y, z in rows:
        factions = ', '.join(f'gamedataAffiliation.{f}' for f in FACTIONS[district])
        out.append(f'    ArrayPush(list, RLArenaCandidate.Make(n"{cid}", "{kind}", "{district}", Vector4({x}, {y}, {z}, 1.0), [{factions}]));')
    out += ['    return list;', '  }', '}', '']
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(out))
    print(f'Wrote {len(rows)} candidates to {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()

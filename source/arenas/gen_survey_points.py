#!/usr/bin/env python3
"""Night City Roguelite - points for the city survey (developers).

    python3 gen_survey_points.py pins_pos.json

pins_pos.json is every quest map pin with its position: a list of
[journal path, variant, x, y, z], read from ep1's 03_night_city.mappins and
joined to cooked_journal.journal (see DEVELOPER_NOTES, "New arenas"). Adds
Appearance Menu Mod's location list when its db.sqlite3 is given as AMM_DB.

Keeps one point per 70 m and floor (8 m), drops the far-off ones (space,
the border) and everything within 90 m of a point the arena scout already
measured (candidates.tsv). Writes survey_points.tsv (index, source, x, y, z)
and r6/scripts/NightCityRoguelite/Data/SurveyPoints.reds.
"""
import json
import math
import os
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'r6', 'scripts', 'NightCityRoguelite', 'Data', 'SurveyPoints.reds')


def near(a, b, reach):
    return math.hypot(a[0] - b[0], a[1] - b[1]) < reach and abs(a[2] - b[2]) < 8


def main():
    points = [(path, x, y, z) for path, _, x, y, z in json.load(open(sys.argv[1])) if x is not None]
    amm = os.environ.get('AMM_DB')
    if amm:
        for name, x, y, z in sqlite3.connect(amm).execute('select loc_name, x, y, z from locations'):
            points.append(('amm/' + name, x, y, z))
    scouted = []
    for line in open(os.path.join(HERE, 'candidates.tsv')):
        if line.startswith('#') or not line.strip():
            continue
        _, _, _, x, y, z = line.rstrip('\n').split('\t')
        scouted.append((float(x), float(y), float(z)))
    keep = []
    for path, x, y, z in points:
        if 'q201_heir' in path or 'cosmos' in path or z > 900 or x > 6000 or y < -7000:
            continue
        p = (x, y, z)
        if any(near(p, s, 90) for s in scouted) or any(near(p, k[1:], 70) for k in keep):
            continue
        keep.append((path, x, y, z))
    with open(os.path.join(HERE, 'survey_points.tsv'), 'w') as fh:
        fh.write('# City survey points (gen_survey_points.py): index, source, x, y, z.\n')
        for i, (path, x, y, z) in enumerate(keep):
            fh.write(f'{i}\t{path}\t{x:.1f}\t{y:.1f}\t{z:.1f}\n')
    lines = [
        '// -----------------------------------------------------------------------------',
        '// Night City Roguelite - city survey points (generated)',
        '// -----------------------------------------------------------------------------',
        '// Generated by source/arenas/gen_survey_points.py (sources in',
        f'// source/arenas/survey_points.tsv). {len(keep)} points for the city survey',
        '// (Dev/CitySurvey.reds, developers only); the index is the point\'s id.',
        '// -----------------------------------------------------------------------------',
        '',
        'module NightCityRoguelite',
        '',
        'public abstract class RLSurveyPoints {',
        '  public static func All() -> array<Vector4> {',
        '    return [',
    ]
    body = [f'      Vector4({x:.1f}, {y:.1f}, {z:.1f}, 1.0)' for _, x, y, z in keep]
    lines.append(',\n'.join(body))
    lines += ['    ];', '  }', '}', '']
    open(OUT, 'w').write('\n'.join(lines))
    print(f'{len(keep)} survey points.')


if __name__ == '__main__':
    main()

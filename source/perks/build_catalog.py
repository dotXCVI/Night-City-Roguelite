#!/usr/bin/env python3
"""catalog.tsv -> r6/scripts/NightCityRoguelite/Rewards/PerkCatalogData.reds.

The curated perk cards: game perk, card name, power (1 novice .. 4 master),
build tags and the card text. Names and effects come from the game's own
English perk texts (2.5).
"""
import os
here = os.path.dirname(os.path.abspath(__file__))
rows = []
for line in open(os.path.join(here, 'catalog.tsv'), encoding='utf-8'):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    perk, name, power, tags, text = line.split('\t')
    rows.append((perk, name, int(power), tags.split(','), text))
esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
out = []
for perk, name, power, tags, text in rows:
    tag_list = ', '.join(f'n"{t}"' for t in tags)
    out.append(f'    RLPerkCatalog.Add(list, gamedataNewPerkType.{perk}, "{esc(name)}", {power}, [{tag_list}], "{esc(text)}");')
body = '\n'.join(out)
dst = os.path.join(here, '..', '..', 'r6', 'scripts', 'NightCityRoguelite', 'Rewards', 'PerkCatalogData.reds')
open(dst, 'w', encoding='utf-8').write(f'''// -----------------------------------------------------------------------------
// Night City Roguelite - perk card data (generated)
// -----------------------------------------------------------------------------
// Generated by source/perks/build_catalog.py from source/perks/catalog.tsv -
// edit the TSV, not this file. {len(rows)} perks.
// -----------------------------------------------------------------------------

module NightCityRoguelite

public abstract class RLPerkCatalogData {{
  public static func Build() -> array<ref<RLPerkDef>> {{
    let list: array<ref<RLPerkDef>>;
{body}
    return list;
  }}
}}
''')
print(len(rows), 'perks')

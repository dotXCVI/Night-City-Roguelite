#!/usr/bin/env python3
"""Generates the mod's TweakXL files and English strings.

  r6/tweaks/NightCityRoguelite/enemies.yaml   roguelite variants of every roster NPC
  r6/tweaks/NightCityRoguelite/effects.yaml   the Drone Escort's drone
  r6/tweaks/NightCityRoguelite/terminal.yaml  the apartment computer's prompt
  source/localization/en-us.tsv               strings for the ArchiveXL localization

Run from the mod root: python3 source/tweaks/gen_tweaks.py
The enemy list is read from r6/scripts/NightCityRoguelite/Data/EnemyRoster.reds.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'r6', 'tweaks', 'NightCityRoguelite')
LOC = os.path.join(ROOT, 'source', 'localization')
os.makedirs(OUT, exist_ok=True)
os.makedirs(LOC, exist_ok=True)

HEADER = """# -----------------------------------------------------------------------------
# Night City Roguelite - {title}
# Generated by source/tweaks/gen_tweaks.py - edit the generator, not this file.
# -----------------------------------------------------------------------------
"""

strings = []  # (secondaryKey, text)

# --- Enemies --------------------------------------------------------------------
roster_src = open(os.path.join(ROOT, 'r6/scripts/NightCityRoguelite/Data/EnemyRoster.reds')).read()
# Every quoted name from the faction lists through the boss lists.
roster = roster_src.split('public static func Records', 1)[1].split('public static func PickUsable', 1)[0]
all_names = sorted(set(re.findall(r'"([A-Za-z0-9_]+)"', roster)))
assert len(all_names) >= 280, len(all_names)

y = [HEADER.format(title='enemy variants')]
y.append("""# Every arena enemy is a copy of one of the game's open-world combat NPCs with
# a few changes:
#   - hostile to V from the start (attitude group "hostile"), and all arena
#     enemies are on the same side, so a boss squad and its adds never fight;
#   - combat senses from the start instead of "relaxed" (they notice V at once);
#   - no dropped weapon, no money, no random weapon injection; bodies carry
#     only this mod's loot table (health items and grenades) - ammo for V's
#     weapons is added by the scripts;
#   - levels still follow V (DeviceContentAssignment.Autoscaling, as before).

NCRoguelite.EnemyLoot:
  $type: LootTable
  lootGenerationType: dropChance
  minItemsToLoot: 0
  maxItemsToLoot: 2
  lootItems:
    - $type: LootItem
      itemID: Items.FirstAidWhiffV0
      dropChance: 0.3
    - $type: LootItem
      itemID: Items.GrenadeFragRegular
      dropChance: 0.2

NCRoguelite.NoLootInjection:
  $type: LootInjectionSettings
  brokenChance: 0.0
  brokenOverrideChance: 0.0
  injectedLoot: None

""")
for n in all_names:
    y.append(f"""NCRoguelite.{n}:
  $base: Character.{n}
  baseAttitudeGroup: hostile
  sensePreset: Senses.Combat
  contentAssignment: DeviceContentAssignment.Autoscaling
  lootDrop: NCRoguelite.EnemyLoot
  lootInjectionParams: NCRoguelite.NoLootInjection
  dropsWeaponOnDeath: false
  dropsMoneyOnDeath: false

""")
open(os.path.join(OUT, 'enemies.yaml'), 'w').write(''.join(y).rstrip() + '\n')

# --- Effects -----------------------------------------------------------------------
# Drone Escort (a prototype, off unless RLConfig.DroneEscort): a Militech drone
# in the player's attitude group, so it fights the arena's enemies. Effects
# themselves need no records: they show on the run HUD, not the buff bar.
e = [HEADER.format(title='effects')]
e.append("""# The Drone Escort effect's drone (Rewards/BoonEffects.reds, RLDrone): a
# Militech Wyvern on V's side, without loot.

NCRoguelite.EscortDrone:
  $base: Character.bls_se_militech_drone_wyvern_easy
  baseAttitudeGroup: player
  sensePreset: Senses.Combat
  lootDrop: NCRoguelite.EnemyLoot
  dropsMoneyOnDeath: false
""")
open(os.path.join(OUT, 'effects.yaml'), 'w').write(''.join(e))
stale = os.path.join(OUT, 'boons.yaml')
if os.path.exists(stale):
    os.remove(stale)

# --- Terminal prompt ---------------------------------------------------------------
strings.append(('NCRoguelite-Interaction-Terminal', 'Roguelite Terminal'))
t = [HEADER.format(title='apartment terminal')]
t.append("""# The prompt shown on V's desk computer while it works as the roguelite
# terminal (a press of the interact key, like "Use").

NCRoguelite.TerminalInteraction:
  $base: Interactions.EnterZoomInteraction
  caption: LocKey#NCRoguelite-Interaction-Terminal
  action: Choice1

# The armory's stash opens the kit picker. "Gear" is the game's own string.

NCRoguelite.ArmoryInteraction:
  $base: Interactions.EnterZoomInteraction
  caption: LocKey#38734
  action: Choice1
""")
open(os.path.join(OUT, 'terminal.yaml'), 'w').write(''.join(t))

with open(os.path.join(LOC, 'en-us.tsv'), 'w') as f:
    for k, v in strings:
        f.write(f'{k}\t{v}\n')
print(f'{len(all_names)} enemy variants, {len(strings)} strings')
